#!/usr/bin/env python3
"""Build assets/world-110m.js — country outlines for BBG.spatial's world base map.

Source: Natural Earth 1:110m Admin 0 countries, v5.1.2 (public domain,
https://www.naturalearthdata.com/about/terms-of-use/). The script downloads the
pinned GeoJSON, keeps only each country's code, name and outline rings, rounds
coordinates to 0.1 degree, and writes one JavaScript file:

    window.BBG_WORLD = { "USA": { "name": "United States of America", "rings": [[lon, lat, lon, lat, …], …] }, … }

Usage (from the repo root):
    python3 .claude/skills/diagram-bytebytego-concept/scripts/build_world.py
"""

import json
import urllib.request
from pathlib import Path

URL = ("https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/"
       "geojson/ne_110m_admin_0_countries.geojson")
OUT = Path(__file__).resolve().parent.parent / "assets" / "world-110m.js"


def rings(geometry: dict) -> list:
    polys = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    out = []
    for poly in polys:
        outer = poly[0]  # holes are not needed at this scale
        flat = []
        for lon, lat in outer:
            flat += [round(lon, 1), round(lat, 1)]
        out.append(flat)
    return out


def main() -> None:
    with urllib.request.urlopen(URL) as resp:
        data = json.load(resp)
    world = {}
    for f in data["features"]:
        p = f["properties"]
        world[p["ADM0_A3"]] = {"name": p["NAME"], "rings": rings(f["geometry"])}
    body = json.dumps(world, separators=(",", ":"))
    OUT.write_text(
        "// Country outlines for BBG.spatial: Natural Earth 1:110m Admin 0 countries v5.1.2 (public domain).\n"
        "// Generated by scripts/build_world.py; keys are ADM0_A3 codes, rings are flat [lon, lat, …] lists.\n"
        f"window.BBG_WORLD = {body};\n"
    )
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB, {len(world)} countries)")


if __name__ == "__main__":
    main()
